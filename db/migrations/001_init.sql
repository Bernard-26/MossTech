-- MOSSTECH schema for PostgreSQL (replaces the SQLite tables that used to be created in server/db.js).
-- CITEXT keeps the old "COLLATE NOCASE" behaviour: usernames and emails are unique ignoring case.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       CITEXT NOT NULL UNIQUE,
  email          CITEXT NOT NULL UNIQUE,
  role           TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  pw_hash        TEXT NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  email_verified INTEGER NOT NULL DEFAULT 0,
  totp_secret    TEXT,
  totp_enabled   INTEGER NOT NULL DEFAULT 0,
  totp_last_step BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,          -- milliseconds since epoch
  last_seen  BIGINT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE products (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             TEXT NOT NULL,
  price            NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  stock            INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  image_url        TEXT NOT NULL DEFAULT 'pics/default.jpg',
  category         TEXT NOT NULL DEFAULT 'other',
  brand            TEXT NOT NULL DEFAULT '',
  discount_percent INTEGER NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 90)
);

CREATE TABLE orders (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number     TEXT NOT NULL UNIQUE,
  user_id          INTEGER REFERENCES users(id) ON DELETE SET NULL,
  customer_name    TEXT NOT NULL,
  customer_email   TEXT NOT NULL,
  customer_phone   TEXT NOT NULL,
  customer_address TEXT NOT NULL,
  payment_method   TEXT NOT NULL,
  total_amount     NUMERIC(14,2) NOT NULL,
  order_date       TEXT NOT NULL,       -- YYYY-MM-DD, kept as text exactly like before
  status           TEXT NOT NULL DEFAULT 'Processing'
);
CREATE INDEX idx_orders_email ON orders(customer_email);
CREATE INDEX idx_orders_user  ON orders(user_id);

CREATE TABLE order_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER,
  name       TEXT NOT NULL,
  price      NUMERIC(12,2) NOT NULL,
  quantity   INTEGER NOT NULL
);
CREATE INDEX idx_order_items_order ON order_items(order_id);

CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE email_verifications (
  user_id    INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  code_hash  TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  tries      INTEGER NOT NULL DEFAULT 0,
  sent_at    BIGINT NOT NULL
);

CREATE TABLE totp_backup (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash TEXT NOT NULL,
  used      INTEGER NOT NULL DEFAULT 0
);

-- Failed-attempt counters / lockouts live in the database so a server restart does not clear them
CREATE TABLE lockouts (
  key       TEXT PRIMARY KEY,
  count     INTEGER NOT NULL DEFAULT 0,
  last_fail BIGINT NOT NULL,
  until     BIGINT NOT NULL DEFAULT 0
);

-- Security audit trail (logins, resets, admin actions). Never stores passwords, codes or tokens.
CREATE TABLE audit_log (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts       BIGINT NOT NULL,
  user_id  INTEGER,
  username TEXT,
  action   TEXT NOT NULL,
  detail   TEXT NOT NULL DEFAULT '',
  ip       TEXT
);
CREATE INDEX idx_audit_ts ON audit_log(ts);
